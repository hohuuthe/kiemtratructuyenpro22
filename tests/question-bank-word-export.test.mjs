test('Availability groups count every owned question exactly once, including aliases and unassigned lessons', () => {
  const inventory = buildQuestionBankExportInventory(dataset, owner);
  assert.equal(inventory.totalAvailable, 8);
  assert.equal(inventory.lessonKeys.length, 5);
  assert.deepEqual(inventory.lessonKeys, ['Bài 1','Bài 2','Bài 3','Bài 10','Chung']);
  assert.equal(inventory.byType['4-1'], 3);
  assert.equal(inventory.byType.TF4, 2);
  assert.equal(inventory.byType.SQ, 1);
  assert.equal(inventory.byType.TL, 2);
  assert.equal(inventory.groups.reduce((sum, g) => sum + g.available, 0), 8);
  assert.equal(dataset[1].type, 'trac_nghiem', 'source data is never mutated');
});

test('Live UI totals and exported question IDs are generated by the same strict selection plan', () => {
  const inventory = buildQuestionBankExportInventory(dataset, owner);
  const choices = [
    {lesson:'Bài 2',type:'4-1',count:1},
    {lesson:'Bài 1',type:'SQ',count:1},
    {lesson:'Bài 10',type:'4-1',count:0},
    {lesson:'Bài 10',type:'TF4',count:1},
    {lesson:'Chung',type:'TF4',count:1}
  ];
  const plan = buildQuestionBankExportPlan(inventory, choices, 'by_lesson');
  assert.equal(plan.requestedCount, 4);
  assert.equal(plan.totalSelected, 4);
  assert.equal(plan.selectedLessons, 4);
  assert.deepEqual(plan.ids, ['B05','B02','B04','B07']);
  assert.deepEqual({ ...plan.perType }, { '4-1':1, SQ:1, TF4:2 });
  assert.equal(plan.questions.some(q=>q.id==='OTHER'), false);
  assert.deepEqual(buildQuestionBankExportPlan(inventory, choices, 'by_type').ids, ['B02','B04','B07','B05']);
});

test('No duplicates, phantom lessons, decimals, out-of-range counts or silently truncated exports', () => {
  const inventory = buildQuestionBankExportInventory(dataset, owner);
  assert.throws(() => buildQuestionBankExportInventory([...dataset,dataset[0]],owner), /trùng/);
  assert.throws(() => buildQuestionBankExportInventory([...dataset,{creatorId:owner,lesson:'Bài 2'}],owner), /thiếu ID/);
  for(const invalid of [-1, 1.5, NaN, Infinity, 3, '2', null]) {
    assert.throws(() => buildQuestionBankExportPlan(inventory,[{lesson:'Bài 2',type:'4-1',count:invalid}]), /Số câu/);
  }
  assert.throws(() => buildQuestionBankExportPlan(inventory,[{lesson:'Bài 404',type:'4-1',count:1}]), /không còn tồn tại/);
  assert.throws(() => buildQuestionBankExportPlan(inventory,[
    {lesson:'Bài 2',type:'4-1',count:1},{lesson:'Bài 2',type:'trac_nghiem',count:1}
  ]), /lặp lại/);
  assert.equal(buildQuestionBankExportPlan(inventory,[], 'by_lesson').totalSelected,0);
});

async function docxXml(blob) {
  const bytes = new Uint8Array(await blob.arrayBuffer());
  const zip = await JSZip.loadAsync(bytes);
  return { xml:await zip.file('word/document.xml').async('string'), zip };
}

test('DOCX contains exactly the selected questions, options and answers with editable OMML chemistry, physics and math', async () => {
  const inventory=buildQuestionBankExportInventory(dataset,owner);
  const choices=inventory.groups.map(g=>({lesson:g.lesson,type:g.type,count:g.available}));
  const plan=buildQuestionBankExportPlan(inventory,choices,'by_lesson');
  const blob=await generateQuestionBankDocx(plan, {resolveImage: async()=>({data:png,width:1,height:1})});
  const {xml,zip}=await docxXml(blob);
  assert.equal((xml.match(/Câu \d+:/g)||[]).length,8, 'Every selected question has one heading');
  for(const sample of ['Bài 10 - tính','Bài 2 - phân tử','Lý thuyết tổng hợp','Bài 2 - câu thứ hai']){
    assert.ok(xml.includes(sample), 'Missing source content '+sample);
  }
  assert.ok(!xml.includes('Không thuộc giáo viên đang xuất'));
  assert.match(xml,/<m:oMath\b/, 'Native editable Office Math is required');
  assert.match(xml,/<m:sSub>/, 'Chemical subscripts must be OMML');
  assert.match(xml,/<m:sSup>/, 'Ionic charges must be OMML');
  assert.match(xml,/<m:f>/, 'Fractions must be OMML');
  assert.ok(!xml.includes('\\ce{'), 'Do not leak raw chemistry LaTeX into Word');
  assert.ok(!xml.includes('\\pu{'), 'Do not leak raw units into Word');
  assert.ok(zip.file('word/document.xml'));
  assert.ok(Object.keys(zip.files).some(path=>path.startsWith('word/media/')));
  assert.ok(xml.includes('Đáp án:'));
  assert.ok(blob.size > 4000);
});

test('Every previously malformed historical Word formula uses the shared editable parser in bank export', async () => {
  const catalogue=JSON.parse(readFileSync('tests/fixtures/scientific-formulas-516.json','utf8'));
  const ids=['MAT-022','MAT-079','MAT-086','MAT-088','STR-003','STR-022','STR-030'];
  const source=ids.map((id,i)=>({
    id,creatorId:owner,lesson:'Bài 1',type:'TL',level:'NB',
    content:catalogue.cases.find(row=>row.id===id).latex,answer:'Đúng'
  }));
  const inventory=buildQuestionBankExportInventory(source,owner);
  const plan=buildQuestionBankExportPlan(inventory,[{lesson:'Bài 1',type:'TL',count:7}]);
  const {xml}=await docxXml(await generateQuestionBankDocx(plan));
  assert.equal((xml.match(/Câu \d+:/g)||[]).length,7);
  assert.match(xml,/<m:oMath\b/);
  assert.match(xml,/<m:eqArr>/);
  assert.match(xml,/<m:m>/);
  assert.ok(!xml.includes('\\begin{'),'Bare TeX environment must not leak into DOCX');
});

